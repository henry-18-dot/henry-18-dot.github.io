def validate(package):
    assert package['schemaVersion']==1
    assert len(package['chapters'])==20
    all_ids=set()
    def add_id(value):
        assert value not in all_ids,f'duplicate ID: {value}'
        all_ids.add(value)
    author_ids={author['id'] for author in package['authors']}
    entity_ids={entity['id'] for entity in package['entities']}
    assert len(entity_ids)==len(package['entities'])
    assert len(author_ids)==len(package['authors'])
    for entity in package['entities']:
        add_id(entity['id'])
        if 'authorId' in entity:
            assert entity['authorId'] in author_ids
    pages=[]
    for i,chapter in enumerate(package['chapters'],1):
        add_id(chapter['id'])
        assert chapter['number']==i
        assert len(chapter['pages'])==3
        assert len(chapter['questions'])==3
        for question in chapter['questions']:
            add_id(question['id'])
            assert set(question.get('entityIds',[]))<=entity_ids
        for page in chapter['pages']:
            pages.append(page)
            add_id(page['id'])
            assert len(page['questions'])==3
            assert set(page['entityIds'])<=entity_ids
            assert set(re.findall(r'\]\(entity:([^)]*)\)',page['markdown']))<=entity_ids
            assert page['source']['startLine']==RANGES[i-1][0]
            assert page['source']['endLine']==RANGES[i-1][1]
            assert '；' not in page['markdown']
            for question in page['questions']:
                add_id(question['id'])
                assert set(question.get('entityIds',[]))<=entity_ids
    for review in package['reviews']:
        add_id(review['id'])
        assert review['authorId'] in author_ids
        assert set(review['entityIds'])<=entity_ids
        assert set(re.findall(r'\]\(entity:([^)]*)\)',review['markdown']))<=entity_ids
        for question in review['questions']:
            add_id(question['id'])
    for comment in package['comments']:
        add_id(comment['id'])
        assert comment['authorId'] in author_ids
        assert comment['ai'] is True
        assert comment['likes']==comment['constructive']==comment['mischief']==0
    for _,chapter_pages,_ in DATA:
        for _,prose,_,_,_ in chapter_pages:
            count=len(re.findall(r'[\u4e00-\u9fff]',prose))
            assert 250<=count<=550,count
    return len(pages),sum(len(p['questions']) for p in pages)+sum(len(c['questions']) for c in package['chapters'])+sum(len(r['questions']) for r in package['reviews'])


def link_names(markdown, entity_ids):
    """Apply explicit links longest-first, bounded by each page's known entities."""
    candidates = {}
    primary_names = {ENTITY_BY_ID[entity_id]['name']:entity_id for entity_id in entity_ids}
    for entity_id in entity_ids:
        entity = ENTITY_BY_ID[entity_id]
        for name in [entity['name'],*entity.get('aliases',[])]:
            # Generic role words are context, not stable names.
            if name in ('上校','智者','婴儿'):
                continue
            if name in primary_names and primary_names[name] != entity_id:
                continue
            if name in candidates and candidates[name] != entity_id:
                raise ValueError(f'ambiguous page alias: {name}')
            candidates[name] = entity_id
    names = sorted(candidates,key=len,reverse=True)
    if not names:
        return markdown
    pattern = re.compile('|'.join(re.escape(name) for name in names))
    # Diagrams use plain labels for Mermaid strict-mode compatibility.
    parts = re.split(r'(```mermaid\n.*?\n```)',markdown,flags=re.S)
    return ''.join(part if part.startswith('```mermaid') else pattern.sub(lambda m:f'[{m[0]}](entity:{candidates[m[0]]})',part) for part in parts)

def questions(prefix,texts,entity_ids):
    result=[]
    for i,text in enumerate(texts):
        kind='理解'
        if re.search(r'区别|差别|不同|相似|照应|呼应|两种',text):
            kind='比较'
        if re.search(r'是否|能否|等于|可靠吗|取消|免除',text):
            kind='反驳'
        if re.search(r'应怎样|如何继续|怎样判断|怎样衡量|如何区分',text):
            kind='应用'
        if re.search(r'史料|查证历史',text):
            kind='背景'
        result.append(dict(id=f'{prefix}-q{i+1:02d}',text=text,kind=kind,entityIds=entity_ids))
    return result

